-- ============================================
-- СХЕМА БД — синхронизировано с реальным дампом cnn.sql
-- (реальная БД "CatologistNeuralNetworks", с которой работает приложение)
--
-- Этот файл — справочный. Приложение НЕ создаёт схему само
-- (spring.jpa.hibernate.ddl-auto=validate), поэтому используйте
-- этот файл только для того, чтобы развернуть БД с нуля локально.
-- ============================================

-- pgvector используется в реальной БД (задел под будущий семантический
-- поиск/эмбеддинги), текущие JPA-сущности его не используют.
CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================
-- 1. ТАБЛИЦА КАТЕГОРИЙ
-- ============================================
CREATE TABLE categories (
    id_categories BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

-- ============================================
-- 2. ТАБЛИЦА НЕЙРОСЕТЕЙ
-- ============================================
CREATE TABLE neuronets (
    id_neuronet BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categories BIGINT REFERENCES categories(id_categories),
    name VARCHAR(255) NOT NULL,
    description_network VARCHAR(255),
    extended_description VARCHAR(255),
    neuronet_icon VARCHAR(255),
    available_in_russia BOOLEAN,
    created_at TIMESTAMP(6),

    -- Как использовать
    usage_registration TEXT,
    usage_setup TEXT,
    usage_general TEXT,

    -- Ссылки и цены
    official_url VARCHAR(500),
    api_url VARCHAR(500),
    github_url VARCHAR(500),
    pricing_info TEXT
);

-- ============================================
-- 3. ТАБЛИЦА ПОЛЬЗОВАТЕЛЕЙ
-- ============================================
CREATE TABLE users (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

-- ============================================
-- 4. ТАБЛИЦА ОТЗЫВОВ (ОЦЕНКА + КОММЕНТАРИЙ)
-- ============================================
CREATE TABLE reviews (
    id_review BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_neuronet BIGINT NOT NULL REFERENCES neuronets(id_neuronet),
    id_user BIGINT NOT NULL REFERENCES users(id_user),
    rating INT NOT NULL,
    comment VARCHAR(255),
    created_at TIMESTAMP(6),
    UNIQUE (id_neuronet, id_user)
);

-- ============================================
-- 5. ГОЛОСА ЗА ОТЗЫВЫ (ЛАЙК/ДИЗЛАЙК)
-- ============================================
CREATE TABLE review_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_review BIGINT NOT NULL REFERENCES reviews(id_review) ON DELETE CASCADE,
    id_user BIGINT NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    vote INT NOT NULL CHECK (vote IN (1, -1)),
    UNIQUE (id_review, id_user)
);

-- ============================================
-- 6. ГРУППЫ ТЕГОВ
-- ============================================
CREATE TABLE tag_groups (
    id_tag_group BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE
);

-- ============================================
-- 7. ТЕГИ
-- ============================================
CREATE TABLE tags (
    id_tag BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tag_group BIGINT NOT NULL REFERENCES tag_groups(id_tag_group),
    name VARCHAR(255) NOT NULL UNIQUE
);

-- ============================================
-- 8. СВЯЗЬ НЕЙРОСЕТЕЙ И ТЕГОВ (М:М)
-- ============================================
CREATE TABLE neuronet_tags (
    id_neuronet BIGINT NOT NULL REFERENCES neuronets(id_neuronet),
    id_tag BIGINT NOT NULL REFERENCES tags(id_tag)
);

-- ============================================
-- ИНДЕКСЫ ДЛЯ ПРОИЗВОДИТЕЛЬНОСТИ
-- ============================================
CREATE INDEX idx_neuronets_category ON neuronets(id_categories);
CREATE INDEX idx_neuronets_name ON neuronets(name);
CREATE INDEX idx_neuronets_available ON neuronets(available_in_russia);
CREATE INDEX idx_reviews_neuronet ON reviews(id_neuronet);
CREATE INDEX idx_reviews_user ON reviews(id_user);
CREATE INDEX idx_reviews_rating ON reviews(rating);
CREATE INDEX idx_review_votes_review ON review_votes(id_review);
CREATE INDEX idx_tags_group ON tags(id_tag_group);
CREATE INDEX idx_neuronet_tags_tag ON neuronet_tags(id_tag);

